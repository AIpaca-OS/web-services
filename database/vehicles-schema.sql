-- Minimal local development schema for Vehicle & Credential Management.
-- No driver ownership or governmental verification is implied.
-- Apply once in the same PostgreSQL database used by Routes.
CREATE TABLE IF NOT EXISTS vc_vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR(80) NOT NULL,
    model VARCHAR(80) NOT NULL,
    license_plate VARCHAR(20) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 80),
    year INTEGER NOT NULL CHECK (year BETWEEN 1980 AND 2100),
    status VARCHAR(40) NOT NULL DEFAULT 'PENDING_VERIFICATION',
    CONSTRAINT uk_vc_vehicles_plate UNIQUE (license_plate)
);
